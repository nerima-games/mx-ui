export const UI_TRANSLATION_KEY_COUNT: number = Object.keys(UI_MESSAGES).length + Object.keys(ACHIEVEMENT_TITLES).length

export const translateUiMessage = (
  language: UiLanguage,
  key: UiMessageKey,
  values: UiMessageValues = {},
): string =>
  UI_MESSAGES[key][language].replace(/\{(?<name>[a-zA-Z0-9_]+)\}/gu, (placeholder, name: string) => {
    const value = values[name]
    if (typeof value === 'undefined') {
      return placeholder
    }
    if (typeof value === 'object') {
      return UI_MESSAGES[value.key][language]
    }
    return String(value)
  })

export const translateAchievementTitle = (language: UiLanguage, achievement: AchievementId): string =>
  ACHIEVEMENT_TITLES[achievement][language]
