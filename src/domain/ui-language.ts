/** Decode untrusted host settings without converting unsupported values to English. */
export const decodeUiLanguage = (input: unknown): Result.Result<UiLanguage, UiLanguageFailure> => {
  if (input === 'en' || input === 'ja') {
    return Result.succeed(input)
  }
  return Result.fail({ _tag: 'UnsupportedUiLanguage' })
}

